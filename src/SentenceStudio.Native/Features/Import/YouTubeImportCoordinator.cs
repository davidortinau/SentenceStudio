    public bool CanFetch => CanEdit() && !_isLoadingTranscripts && !string.IsNullOrWhiteSpace(_videoUrl);

    /// <summary>Source FetchTranscripts (the Fetch button and Return in the link field).</summary>
    public async Task FetchTranscriptsAsync()
    {
        if (!CanFetch || !TryOwner(out var owner))
            return;
        var operation = ++_operation;
        var url = _videoUrl;
        var token = _lifetime.Token;
        _isLoadingTranscripts = true;
        _error = null;
        _messages = [];
        _tracks = [];
        _selectedTrack = null;
        _transcriptText = string.Empty;
        _savedResourceId = null;
        Notify();
        try
        {
            // Source: the title is best effort; a failed metadata read leaves it empty.
            try
            {
                _videoTitle = await OffUiAsync(() => _import.GetVideoTitleAsync(owner, url, token));
            }
            catch (Exception ex) when (ex is not UnauthorizedAccessException
                && (ex is not OperationCanceledException || !_disposed))
            {
                _logger.LogInformation(ex, "YouTube import could not read the video title.");
                _videoTitle = null;
            }
            if (!IsCurrent(operation))
                return;
            var tracks = await OffUiAsync(() => _import.GetTracksAsync(owner, url, token));
            if (!IsCurrent(operation) || !TryOwner(out _))
                return;
            _tracks = [.. tracks ?? []];
            if (_tracks.Count == 0)
            {
                _error = NativeMessage.Error("Import_NoTranscripts");
                return;
            }
            // Source: the preferred language's first track, else the first track.
            _selectedTrack = _tracks.FirstOrDefault(track =>
                    track.LanguageCode.StartsWith(_preferredLanguage, StringComparison.OrdinalIgnoreCase))
                ?? _tracks[0];
            await DownloadTranscriptAsync(owner, operation);
        }
        catch (OperationCanceledException) when (_disposed)
        {
        }
        catch (UnauthorizedAccessException ex)
        {
            OnOwnerRefused(ex, operation);
        }
        catch (Exception ex)
        {
            _logger.LogError(ex, "Failed to fetch transcripts");
            if (IsCurrent(operation))
                _error = ErrorWith("YouTubeImport_FetchTranscriptsError", ex.Message);
        }
        finally
        {
            if (IsCurrent(operation))
            {
                _isLoadingTranscripts = false;
                Notify();
            }
        }
    }

    /// <summary>Source OnTranscriptSelected: another track's captions replace the transcript.</summary>
    public async Task SelectTrackAsync(int index)
    {
        if (!CanEdit() || _isLoadingTranscripts || index < 0 || index >= _tracks.Count
            || !TryOwner(out var owner))
            return;
        var operation = ++_operation;
        _selectedTrack = _tracks[index];
        _messages = [];
        try
        {
            await DownloadTranscriptAsync(owner, operation);
        }
        finally
        {
            if (IsCurrent(operation))
                Notify();
        }
    }

    /// <summary>Source DownloadTranscript: failures say so in the page's error.</summary>
    private async Task DownloadTranscriptAsync(string owner, long operation)
    {
        if (_selectedTrack is not { } track)
            return;
        var run = ++_downloadRun;
        _isLoadingTranscript = true;
        Notify();
        try
        {
            var token = _lifetime.Token;
            var text = await OffUiAsync(() => _import.DownloadTranscriptAsync(owner, track, token));
            if (IsCurrent(operation) && TryOwner(out _))
                _transcriptText = text ?? string.Empty;
        }
        catch (OperationCanceledException) when (_disposed)
        {
        }
        catch (UnauthorizedAccessException ex)
        {
            OnOwnerRefused(ex, operation);
        }
        catch (Exception ex)
        {
            _logger.LogError(ex, "Failed to download transcript");
            if (IsCurrent(operation))
                _error = NativeMessage.Error("YouTubeImport_DownloadTranscriptError");
        }
        finally
        {
            // The download is over even when a newer action replaced its result (source: the
            // flag always clears); only a newer download keeps it.
            if (!_disposed && run == _downloadRun)
            {
                _isLoadingTranscript = false;
                if (!IsCurrent(operation))
                    Notify();
            }
        }
    }

    public bool CanPolish => CanEdit() && !_isPolishing && !string.IsNullOrWhiteSpace(_transcriptText);

    /// <summary>Source PolishTranscript: the AI's text replaces the transcript; a toast says how it went.</summary>
    public async Task PolishAsync()
    {
        if (!CanPolish || !TryOwner(out var owner))
            return;
        var operation = ++_operation;
        var run = ++_polishRun;
        var text = _transcriptText;
        var language = _selectedTrack?.LanguageCode;
        var token = _lifetime.Token;
        _isPolishing = true;
        _messages = [];
        Notify();
        try
        {
            var polished = await OffUiAsync(() => _import.PolishAsync(owner, text, language, token));
            if (!IsCurrent(operation) || !TryOwner(out _))
                return;
            _transcriptText = polished;
            _messages = _messages.Add(NativeMessage.Success("Import_TranscriptPolished"));
        }
        catch (OperationCanceledException) when (_disposed)
        {
        }
        catch (UnauthorizedAccessException ex)
        {
            OnOwnerRefused(ex, operation);
        }
        catch (Exception ex)
        {
            _logger.LogError(ex, "Failed to polish transcript");
            if (IsCurrent(operation))
                _messages = _messages.Add(NativeMessage.Error("Import_PolishingFailed"));
        }
        finally
        {
            // Source: the button comes back when the polish ends, also when Fetch, another track
            // or Save replaced its result meanwhile; only a newer polish keeps it busy.
            if (!_disposed && run == _polishRun)
            {
                _isPolishing = false;
                Notify();
            }
        }
    }

    public bool CanSave => CanEdit() && !_isSaving && !string.IsNullOrWhiteSpace(_transcriptText);

    /// <summary>Source SaveAsResource: a "Video" resource with the link and the edited transcript.</summary>
    public async Task SaveAsResourceAsync()
    {
        if (!CanSave || !TryOwner(out var owner))
            return;
        var operation = ++_operation;
        var draft = new NativeYouTubeResourceDraft(
            _videoTitle ?? "YouTube Import",
            _videoUrl,
            _transcriptText,
            NormalizeLanguageName(_selectedTrack?.LanguageName ?? string.Empty));
        _isSaving = true;
        _error = null;
        _messages = [];
        Notify();
        var saved = false;
        try
        {
            // One write: it is not cancelled by leaving the page.
            var result = await OffUiAsync(() => _import.SaveResourceAsync(owner, draft, CancellationToken.None));
            if (_disposed)
                return;
            // Written for the owner the save ran for; a changed owner sees nothing (not a failure).
            if (result.ResourceId is not { Length: > 0 } id || !OwnerIsCurrent())
            {
                _logger.LogWarning("YouTube import saved, but the device owner changed: the result is not shown.");
                Block();
                return;
            }
            saved = true;
            if (operation != _operation)
                return;
            _savedResourceId = id;
            _messages = _messages.Add(NativeMessage.Success("Import_ResourceSaved"));
        }
        catch (UnauthorizedAccessException ex)
        {
            OnOwnerRefused(ex, operation);
        }
        catch (Exception ex)
        {
            _logger.LogError(ex, "Failed to save resource");
            if (operation == _operation)
                _error = ErrorWith("YouTubeImport_SaveResourceError", ex.Message);
        }
        finally
        {
            _isSaving = false;
            Notify();
        }
        if (!saved)
            return;
        // After the saved state is shown: a listener's failure cannot turn a saved video into a
        // failed save (which would invite saving it twice).
        try
        {
            ResourcesWritten?.Invoke();
        }
        catch (Exception ex)
        {
            _logger.LogError(ex, "A listener failed after a YouTube import was saved.");
        }
    }

    /// <summary>Source Reset (Import Another): every single-video field back to its default.</summary>
    public void Reset()
    {
        if (!_open || _disposed || _isSaving)
            return;
        ++_operation;
        _videoUrl = string.Empty;
        _transcriptText = string.Empty;
        _error = null;
        _tracks = [];
        _selectedTrack = null;
        _savedResourceId = null;
        _videoTitle = null;
        _isLoadingTranscripts = false;
        _isLoadingTranscript = false;
        _isPolishing = false;
        _messages = [];
        Notify();
    }

