/// <summary>Source MediaImport.razor Tab (the button group); the page opens on My Channels.</summary>
public enum YouTubeImportTab { Channels, SingleVideo, History }

/// <summary>
/// A My Channels card (source: the channel's name or handle, handle, language, last check, switch).
/// <see cref="IsSaving"/>: the switch's change is being saved, so the switch waits.
/// </summary>
public sealed record YouTubeChannelRow(
    string Id, string? ChannelName, string? ChannelHandle, string? Language,
    DateTime? LastCheckedAt, bool IsActive, bool IsSaving = false);

/// <summary>
/// An Import History row (source: badge, title, channel, date, Retry). <see cref="IsManual"/>
/// rows came from no channel; <see cref="ChannelName"/> is null for a channel with neither a
/// name nor a handle (or one not in the list).
/// </summary>
public sealed record YouTubeImportRow(
    string Id, string? VideoTitle, bool IsManual, string? ChannelName, VideoImportStatus Status,
    string? ErrorMessage, DateTime? CreatedAt, string? LearningResourceId, bool IsStuck)
{
    /// <summary>Source isClickable: a completed import with its resource opens it.</summary>
    public bool IsClickable => Status == VideoImportStatus.Completed
        && !string.IsNullOrEmpty(LearningResourceId);

    public bool IsFailed => Status == VideoImportStatus.Failed;

    /// <summary>Source canRetry: failed, or stuck in progress for more than 10 minutes.</summary>
    public bool CanRetry => IsFailed || IsStuck;
}

/// <summary>A caption track choice (source: the transcript language select's option).</summary>
public sealed record YouTubeTrackOption(int Index, string LanguageCode, string LanguageName, bool IsAutoGenerated);

public sealed record YouTubeImportState(
    bool Open,
    bool Blocked,
    YouTubeImportTab Tab,
    string VideoUrl,
    bool IsLoadingTranscripts,
    bool IsLoadingTranscript,
    bool IsPolishing,
    bool IsSaving,
    ImmutableArray<YouTubeTrackOption> Tracks,
    int SelectedTrack,
    string TranscriptText,
    string? SavedResourceId,
    NativeMessage? Error,
    bool IsLoadingChannels,
    ImmutableArray<YouTubeChannelRow> Channels,
    bool IsLoadingImports,
    ImmutableArray<YouTubeImportRow> DisplayedImports,
    int ImportCount,
    string? RetryingImportId,
    ImmutableArray<NativeMessage> Messages)
{
    /// <summary>Source Fetch button: disabled while fetching or while the link is empty.</summary>
    public bool CanFetch => Open && !Blocked && !IsLoadingTranscripts
        && !string.IsNullOrWhiteSpace(VideoUrl);

    /// <summary>Source: the transcript card shows once tracks were found.</summary>
    public bool HasTracks => !Tracks.IsDefaultOrEmpty;

    /// <summary>Source: the editor and its actions show once a transcript was downloaded.</summary>
    public bool HasTranscript => !string.IsNullOrEmpty(TranscriptText);

    /// <summary>Source Show more: fewer rows shown than the history holds.</summary>
    public bool HasMoreImports => !DisplayedImports.IsDefault && DisplayedImports.Length < ImportCount;
}

/// <summary>
/// The source Media Import page (src/SentenceStudio.UI/Pages/MediaImport.razor, routes
/// /media-import and /import) for one verified owner: My Channels (with the monitoring switch),
/// Single Video (link, caption tracks, language, the editable transcript, Polish with AI, Save as
/// Resource) and Import History (status, Retry, Show more, polling of active imports). The video
/// work runs on the device through the shared YouTube services; channels and history come from
/// the API. An absent or changed owner blocks the screen and nothing is read or written.
/// <see cref="Version"/> changes when the page must be drawn again; typing the link or the
/// transcript only updates the state, as the source bindings do. Service work runs off the UI
/// thread and resumes on the caller's synchronization context.
/// </summary>
public sealed class YouTubeImportCoordinator : IDisposable
{
    /// <summary>Source importsPageSize: rows shown per Show more.</summary>
    public const int ImportsPageSize = 50;

    /// <summary>Source StartPolling: every 5 seconds while an import is in progress.</summary>
    public static readonly TimeSpan PollInterval = TimeSpan.FromSeconds(5);

    /// <summary>Source isStuck: in progress for more than 10 minutes.</summary>
    public static readonly TimeSpan StuckAfter = TimeSpan.FromMinutes(10);

    private readonly INativeYouTubeImport _import;
    private readonly DeviceUserScopeProvider _userScope;
    private readonly ILogger _logger;
    private readonly Func<DateTime> _utcNow;
    private readonly TimeSpan _pollInterval;
    private readonly CancellationTokenSource _lifetime = new();
    private string? _owner;
    private DeviceUserScopeProvider.ScopeStamp _ownerStamp;
    private bool _open;
    private bool _blocked;
    private bool _disposed;
    private long _operation;
    private long _polishRun;
    private long _downloadRun;
    private bool _polling;
    private Task? _pollLoop;

    // Source fields (MediaImport.razor:288-319), with the same defaults.
    private YouTubeImportTab _tab = YouTubeImportTab.Channels;
    private string _videoUrl = string.Empty;
    private string _transcriptText = string.Empty;
    private NativeMessage? _error;
    private string _preferredLanguage = "ko";
    private bool _isLoadingTranscripts;
    private bool _isLoadingTranscript;
    private bool _isPolishing;
    private bool _isSaving;
    private string? _savedResourceId;
    private List<TranscriptTrack> _tracks = [];
    private TranscriptTrack? _selectedTrack;
    private string? _videoTitle;
    private List<MonitoredChannel> _channels = [];
    private bool _isLoadingChannels = true;
    private List<NativeYouTubeImportRecord> _imports = [];
    private bool _isLoadingImports = true;
    private int _importsDisplayCount = ImportsPageSize;
    private string? _retryingImportId;
    private ImmutableArray<NativeMessage> _messages = [];
    private readonly HashSet<string> _savingChannels = new(StringComparer.Ordinal);
    // When this page last retried an import: its stored CreatedAt is still the first run's, so
    // "stuck" counts from the retry (the server would accept a second retry at once).
    private readonly Dictionary<string, DateTime> _retriedAt = new(StringComparer.Ordinal);

    public YouTubeImportCoordinator(INativeYouTubeImport import, DeviceUserScopeProvider userScope,
        ILogger<YouTubeImportCoordinator> logger, Func<DateTime>? utcNow = null,
        TimeSpan? pollInterval = null)
    {
        _import = import;
        _userScope = userScope;
        _logger = logger;
        _utcNow = utcNow ?? (() => DateTime.UtcNow);
        _pollInterval = pollInterval ?? PollInterval;
    }

    /// <summary>Raised when the page must be drawn again (<see cref="Version"/> changed).</summary>
    public event Action? Changed;

    /// <summary>Raised after a save wrote the owner's resource (a head marks its resource list stale).</summary>
    public event Action? ResourcesWritten;

    public long Version { get; private set; }

    public bool IsOpen => _open;

    /// <summary>A save is running: Back waits for its result (source: the button spins).</summary>
    public bool IsNavigationBlocked => _isSaving;

    /// <summary>
    /// A link or transcript that is not saved yet: leaving would lose it, so another tab's entry
    /// shows the page instead of closing it (a saved video holds nothing).
    /// </summary>
    public bool HasUnsavedWork => _open && !_blocked && _savedResourceId is null
        && (!string.IsNullOrWhiteSpace(_transcriptText) || !string.IsNullOrWhiteSpace(_videoUrl));

    public ImmutableArray<NativeMessage> Messages => _messages;

    public YouTubeImportState State
    {
        get
        {
            var tracks = _tracks.Select((track, index) => new YouTubeTrackOption(index,
                track.LanguageCode, track.LanguageName, track.IsAutoGenerated)).ToImmutableArray();
            var now = _utcNow();
            var displayed = _imports.Take(_importsDisplayCount).Select(import => Row(import, now))
                .ToImmutableArray();
            var channels = _channels.Select(channel => new YouTubeChannelRow(channel.Id,
                channel.ChannelName, channel.ChannelHandle, channel.Language, channel.LastCheckedAt,
                channel.IsActive, _savingChannels.Contains(channel.Id))).ToImmutableArray();
            return new(_open, _blocked, _tab, _videoUrl, _isLoadingTranscripts, _isLoadingTranscript,
                _isPolishing, _isSaving, tracks,
                _selectedTrack is null ? -1 : _tracks.IndexOf(_selectedTrack),
                _transcriptText, _savedResourceId, _error, _isLoadingChannels, channels,
                _isLoadingImports, displayed, _imports.Count, _retryingImportId, _messages);
        }
    }

    /// <summary>
    /// Source OnInitializedAsync: the profile's language picks the preferred caption track, then
    /// the channels and the history load together, then the active imports are polled.
    /// </summary>
    public async Task<bool> OpenAsync(string? expectedOwner)
    {
        if (_disposed || _open)
            return false;
        if (string.IsNullOrWhiteSpace(expectedOwner)
            || !_userScope.TryGetUserProfileId(out var active) || active != expectedOwner)
        {
            _logger.LogWarning("YouTube import refused an absent or untrusted owner.");
            return false;
        }
        var stamp = _userScope.CaptureStamp();
        if (stamp.PublishedOwner != expectedOwner || !_userScope.IsCurrent(stamp))
        {
            _logger.LogWarning("YouTube import refused a changed owner.");
            return false;
        }
        _owner = expectedOwner;
        _ownerStamp = stamp;
        _open = true;
        Notify();
        var token = _lifetime.Token;
        try
        {
            var language = await OffUiAsync(() => _import.GetTargetLanguageAsync(expectedOwner, token));
            _preferredLanguage = PreferredLanguageCode(language ?? "Korean");
        }
        catch (OperationCanceledException) when (_disposed)
        {
            return false;
        }
        catch (UnauthorizedAccessException ex)
        {
            OnOwnerRefused(ex, _operation);
            return false;
        }
        catch (Exception ex)
        {
            // Source: a failed profile read keeps the default ("ko").
            _logger.LogWarning(ex, "YouTube import could not read the profile language.");
        }
        if (!TryOwner(out _))
            return false;
        await Task.WhenAll(LoadChannelsAsync(announce: false), LoadImportsAsync(announce: false));
        if (!TryOwner(out _))
            return false;
        StartPolling();
        return true;
    }

    /// <summary>Source SwitchTab: the tab changes and the single video's error clears.</summary>
    public void SwitchTab(YouTubeImportTab tab)
    {
        if (!_open || _disposed || !Enum.IsDefined(tab))
            return;
        _tab = tab;
        _error = null;
        // The learner's next action clears the banners (Captain, 2026-11-02).
        _messages = [];
        Notify();
    }

