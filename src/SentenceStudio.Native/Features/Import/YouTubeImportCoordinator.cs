    {
        if (!_open || _blocked || _disposed)
            return;
        _messages = [];
        await LoadImportsAsync(announce: true);
        if (_open && !_blocked && !_disposed && !_messages.Any(message => message.IsError))
        {
            _messages = _messages.Add(NativeMessage.Success("Import_ImportsRefreshed"));
            Notify();
        }
    }

    /// <summary>Source ShowMoreImports.</summary>
    public void ShowMoreImports()
    {
        if (!_open || _disposed)
            return;
        _importsDisplayCount += ImportsPageSize;
        Notify();
    }

    /// <summary>
    /// Source OnImportRowClick: a completed import returns its resource to open; a failed one
    /// shows its error. Returns null when nothing opens.
    /// </summary>
    public string? OpenImport(string importId)
    {
        if (!_open || _blocked || _disposed)
            return null;
        var import = _imports.FirstOrDefault(row => row.Id == importId);
        if (import is null)
            return null;
        if (import.Status == VideoImportStatus.Completed && !string.IsNullOrEmpty(import.LearningResourceId))
            return import.LearningResourceId;
        if (import.Status == VideoImportStatus.Failed && !string.IsNullOrEmpty(import.ErrorMessage))
        {
            _messages = [new NativeMessage(NativeMessageKind.Error, null, import.ErrorMessage)];
            Notify();
        }
        return null;
    }

    /// <summary>
    /// Source RetryImport: the import runs again on the server; the row shows Pending at once and
    /// the polling follows it.
    /// </summary>
    public async Task RetryImportAsync(string importId)
    {
        if (!_open || _blocked || _disposed || _retryingImportId is not null || !TryOwner(out var owner))
            return;
        var index = _imports.FindIndex(row => row.Id == importId);
        if (index < 0)
            return;
        var import = _imports[index];
        if (Row(import, _utcNow()) is not { CanRetry: true })
            return;
        _retryingImportId = importId;
        _messages = [];
        Notify();
        try
        {
            var token = _lifetime.Token;
            await OffUiAsync(async () =>
            {
                await _import.RetryImportAsync(owner, importId, token);
                return true;
            });
            if (_disposed || !TryOwner(out _))
                return;
            var current = _imports.FindIndex(row => row.Id == importId);
            if (current >= 0)
                _imports[current] = _imports[current] with
                {
                    Status = VideoImportStatus.Pending,
                    ErrorMessage = null
                };
            // Retry hides until the row fails or is stuck again counting from now.
            _retriedAt[importId] = _utcNow();
            _messages = _messages.Add(NativeMessage.Info("YouTubeImport_Retrying",
                import.VideoTitle ?? string.Empty));
            StartPolling();
        }
        catch (OperationCanceledException) when (_disposed)
        {
        }
        catch (UnauthorizedAccessException ex)
        {
            OnOwnerRefused(ex, _operation);
        }
        catch (Exception ex)
        {
            _logger.LogError(ex, "Failed to retry import {Id}", importId);
            if (!_disposed)
                _messages = _messages.Add(ErrorWith("YouTubeImport_RetryFailed", ex.Message));
        }
        finally
        {
            if (!_disposed)
            {
                _retryingImportId = null;
                Notify();
            }
        }
    }

    /// <summary>
    /// Source StartPolling: one loop for the page's life; each tick reads the history again when
    /// an import is in progress and updates those rows' status, error, resource and completion.
    /// </summary>
    private void StartPolling()
    {
        if (_pollLoop is not null || _disposed)
            return;
        _pollLoop = PollAsync(_lifetime.Token);
    }

    private async Task PollAsync(CancellationToken token)
    {
        try
        {
            while (!token.IsCancellationRequested)
            {
                await Task.Delay(_pollInterval, token);
                await PollOnceAsync(token);
            }
        }
        catch (OperationCanceledException) when (token.IsCancellationRequested)
        {
        }
    }

    /// <summary>One poll (internal for tests): reads the history only while an import is active.</summary>
    internal async Task PollOnceAsync(CancellationToken token)
    {
        if (_polling || _blocked || !_open || !_imports.Any(IsActive) || !TryOwner(out var owner))
            return;
        _polling = true;
        try
        {
            var updated = await OffUiAsync(() => _import.ListImportsAsync(owner, token));
            if (_disposed || !TryOwner(out _))
                return;
            var byId = updated.ToDictionary(row => row.Id, StringComparer.Ordinal);
            for (var index = 0; index < _imports.Count; index++)
            {
                if (byId.TryGetValue(_imports[index].Id, out var row))
                    _imports[index] = _imports[index] with
                    {
                        Status = row.Status,
                        ErrorMessage = row.ErrorMessage,
                        LearningResourceId = row.LearningResourceId,
                        CompletedAt = row.CompletedAt
                    };
            }
            Notify();
        }
        catch (OperationCanceledException) when (token.IsCancellationRequested)
        {
        }
        catch (UnauthorizedAccessException ex)
        {
            OnOwnerRefused(ex, _operation);
        }
        catch (Exception ex)
        {
            // Source: a polling error is logged; the next tick tries again.
            _logger.LogError(ex, "Polling error");
        }
        finally
        {
            _polling = false;
        }
    }

    /// <summary>
    /// A message from the channel page shown here after it closed (source: the toast of a saved
    /// channel shows on the Media Import page it returns to).
    /// </summary>
    public void ShowMessage(NativeMessage message)
    {
        ArgumentNullException.ThrowIfNull(message);
        if (!_open || _disposed)
            return;
        _messages = [message];
        Notify();
    }

    /// <summary>
    /// Source: the channel page's Save and Cancel navigate to /media-import, which loads its
    /// channels and history again (a channel saved before an edit page's Cancel shows, as do the
    /// imports it started).
    /// </summary>
    public async Task ReloadAfterChannelPageAsync()
    {
        if (!_open || _blocked || _disposed)
            return;
        var messages = _messages;
        await Task.WhenAll(LoadChannelsAsync(announce: true), LoadImportsAsync(announce: true));
        if (!_disposed && _messages.IsEmpty && !messages.IsEmpty)
        {
            _messages = messages;
            Notify();
        }
    }

    public void DismissMessages()
    {
        if (_messages.IsEmpty)
            return;
        _messages = [];
        Notify();
    }

    public void Dispose()
    {
        if (_disposed)
            return;
        _disposed = true;
        _open = false;
        _lifetime.Cancel();
        _lifetime.Dispose();
    }

    // ---- Helpers ----

    private static bool IsActive(NativeYouTubeImportRecord import) =>
        import.Status is not (VideoImportStatus.Completed or VideoImportStatus.Failed);

    private YouTubeImportRow Row(NativeYouTubeImportRecord import, DateTime now)
    {
        var manual = string.IsNullOrEmpty(import.MonitoredChannelId);
        var channel = manual ? null : _channels.FirstOrDefault(row => row.Id == import.MonitoredChannelId);
        // An import without its creation time (an API before B79) is never taken as stuck. The
        // time is compared as an instant: one sent with an offset parses as device-local time.
        // A row this page retried counts from the retry: its CreatedAt is still the first run's.
        var since = import.CreatedAt?.ToUniversalTime();
        if (_retriedAt.TryGetValue(import.Id, out var retried) && (since is null || retried > since))
            since = retried;
        var stuck = import.Status != VideoImportStatus.Failed
            && import.Status != VideoImportStatus.Completed
            && since is { } from && from < now - StuckAfter;
        return new(import.Id, import.VideoTitle, manual, channel?.ChannelName ?? channel?.ChannelHandle,
            import.Status, import.ErrorMessage, import.CreatedAt, import.LearningResourceId, stuck);
    }

    /// <summary>Source OnInitializedAsync's language code for the profile's target language.</summary>
    internal static string PreferredLanguageCode(string language) => language.ToLowerInvariant() switch
    {
        "korean" => "ko",
        "japanese" => "ja",
        "chinese" => "zh",
        "spanish" => "es",
        "french" => "fr",
        "german" => "de",
        _ => language[..Math.Min(2, language.Length)].ToLowerInvariant()
    };

    /// <summary>Source NormalizeLanguageName: the track's name without a "(...)" suffix.</summary>
    internal static string NormalizeLanguageName(string language)
    {
        if (string.IsNullOrWhiteSpace(language))
            return language;
        var parenIndex = language.IndexOf('(');
        if (parenIndex > 0)
            language = language[..parenIndex];
        return language.Trim();
    }

    /// <summary>Runs service work off the UI thread; the caller resumes on its synchronization context.</summary>
    private static Task<T> OffUiAsync<T>(Func<Task<T>> work) => Task.Run(work);

    private bool CanEdit() => _open && !_blocked && !_disposed && !_isSaving;

    private bool IsCurrent(long operation) => !_disposed && operation == _operation;

    private bool OwnerIsCurrent() =>
        !_disposed && _open && !_blocked && !string.IsNullOrWhiteSpace(_owner)
        && _userScope.IsCurrent(_ownerStamp)
        && _userScope.TryGetUserProfileId(out var active) && active == _owner;

    private bool TryOwner(out string owner)
    {
        owner = _owner ?? string.Empty;
        if (_disposed || !_open || _blocked || string.IsNullOrWhiteSpace(_owner))
            return false;
        if (OwnerIsCurrent())
            return true;
        _logger.LogWarning("YouTube import stopped: the device owner changed.");
        Block();
        Notify();
        return false;
    }

    private void OnOwnerRefused(UnauthorizedAccessException ex, long operation)
    {
        _logger.LogWarning(ex, "YouTube import was refused for an absent or changed owner.");
        if (_disposed)
            return;
        Block();
        Notify();
    }

    private void Block()
    {
        _blocked = true;
        _isLoadingTranscripts = false;
        _isLoadingTranscript = false;
        _isPolishing = false;
    }

    /// <summary>The resource's text, then ": " and the exception message (source: "Error ...: {ex.Message}").</summary>
    private static NativeMessage ErrorWith(string key, string detail) =>
        new(NativeMessageKind.Error, key, detail);

    private void Notify()
    {
        if (_disposed)
            return;
        Version++;
        Changed?.Invoke();
    }
